#!/usr/bin/env python3
"""Produce machine-readable evidence for the exact current checkout."""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

from cutsignal.privacy import audit_paths

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "artifacts"
EXCLUDED_PARTS = {".git", ".mypy_cache", ".pytest_cache", ".ruff_cache", "__pycache__", "artifacts"}
VERIFIER_OWNED_FILES = (
    "coverage.json",
    "cases.json",
    "synthetic-evaluation.json",
    "fresh-install.json",
    "verification.json",
    "score.json",
    "SCORECARD.md",
)
VERIFIER_OWNED_DIRECTORIES = ("dist", "e2e")
SCORE_CRITICAL_ARTIFACTS = {
    "coverage",
    "cases",
    "synthetic_evaluation",
    "fresh_install",
    "e2e_summary",
    "wheel",
    "source_distribution",
}


def checkout_files() -> list[Path]:
    """Return every tracked or non-ignored untracked file in the publishable checkout."""
    git_binary = shutil.which("git")
    if git_binary is not None:
        listed = subprocess.run(  # noqa: S603
            [git_binary, "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
            cwd=ROOT,
            capture_output=True,
            check=True,
        ).stdout
        return sorted(
            ROOT / relative.decode("utf-8")
            for relative in listed.split(b"\0")
            if relative and (ROOT / relative.decode("utf-8")).is_file()
        )
    return sorted(
        path
        for path in ROOT.rglob("*")
        if path.is_file()
        and ".venv" not in path.relative_to(ROOT).parts
        and not EXCLUDED_PARTS.intersection(path.relative_to(ROOT).parts)
    )


def checkout_fingerprint() -> str:
    digest = hashlib.sha256()
    files = checkout_files()
    for path in files:
        relative = path.relative_to(ROOT).as_posix()
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def file_evidence(path: Path) -> dict[str, str | int]:
    """Return a repository-relative, content-addressed file record."""
    return {
        "path": path.relative_to(ROOT).as_posix(),
        "bytes": path.stat().st_size,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }


def reset_verifier_outputs() -> None:
    """Remove only paths owned and regenerated by this verifier."""
    ARTIFACTS.mkdir(parents=True, exist_ok=True)
    for relative in VERIFIER_OWNED_FILES:
        (ARTIFACTS / relative).unlink(missing_ok=True)
    for relative in VERIFIER_OWNED_DIRECTORIES:
        destination = ARTIFACTS / relative
        if destination.exists():
            shutil.rmtree(destination)


def _captured_text(value: str | bytes | None) -> str:
    if value is None:
        return ""
    return value.decode("utf-8", errors="replace") if isinstance(value, bytes) else value


def _run(name: str, command: list[str], timeout: int = 180) -> dict[str, Any]:
    started = time.monotonic()
    print(f"[verify] {name}: running", flush=True)
    environment = os.environ.copy()
    environment["PYTHONHASHSEED"] = "0"
    try:
        result = subprocess.run(  # noqa: S603
            command,
            cwd=ROOT,
            env=environment,
            text=True,
            capture_output=True,
            timeout=timeout,
            check=False,
        )
        output = (result.stdout + "\n" + result.stderr).strip()
        evidence = {
            "name": name,
            "passed": result.returncode == 0,
            "returncode": result.returncode,
            "duration_seconds": round(time.monotonic() - started, 3),
            "command": command,
            "output_tail": output[-12_000:],
        }
        state = "passed" if evidence["passed"] else "failed"
        print(f"[verify] {name}: {state} ({evidence['duration_seconds']}s)", flush=True)
        return evidence
    except subprocess.TimeoutExpired as exc:
        captured = "\n".join(part for part in (_captured_text(exc.stdout), _captured_text(exc.stderr)) if part)
        evidence = {
            "name": name,
            "passed": False,
            "returncode": None,
            "duration_seconds": round(time.monotonic() - started, 3),
            "command": command,
            "output_tail": (f"timed out: {exc}\n{captured}").strip()[-12_000:],
        }
        print(f"[verify] {name}: timed out ({evidence['duration_seconds']}s)", flush=True)
        return evidence


def main() -> int:
    reset_verifier_outputs()
    python = sys.executable
    checks = {
        "ruff_check": _run("ruff_check", [python, "-m", "ruff", "check", "."]),
        "ruff_format": _run("ruff_format", [python, "-m", "ruff", "format", "--check", "."]),
        "mypy": _run("mypy", [python, "-m", "mypy", "src/cutsignal"]),
        "pytest_coverage": _run(
            "pytest_coverage",
            [
                python,
                "-m",
                "pytest",
                "--cov=cutsignal",
                "--cov-report=term-missing",
                "--cov-report=json:artifacts/coverage.json",
            ],
        ),
        "wheel": _run(
            "distribution",
            [python, "-m", "build", "--sdist", "--wheel", "--outdir", "artifacts/dist"],
        ),
        "fresh_install": _run(
            "fresh_install",
            [python, "scripts/fresh_install_smoke.py"],
            timeout=900,
        ),
        "pip_check": _run("pip_check", [python, "-m", "pip", "check"]),
        "dependency_audit": _run(
            "dependency_audit",
            [
                python,
                "-m",
                "pip_audit",
                "--skip-editable",
                "--progress-spinner",
                "off",
                "--vulnerability-service",
                "osv",
                "--timeout",
                "60",
            ],
            timeout=240,
        ),
        "public_api": _run(
            "public_api",
            [
                python,
                "-c",
                (
                    "import cutsignal; "
                    "assert callable(cutsignal.analyze_cut); "
                    "assert callable(cutsignal.analyze_strength); "
                    "assert callable(cutsignal.optimize_weekly_plan); "
                    "assert callable(cutsignal.run_pipeline)"
                ),
            ],
        ),
        "version_consistency": _run(
            "version_consistency",
            [python, "scripts/verify_versions.py"],
        ),
        "claims": _run("claims", [python, "scripts/verify_claims.py"]),
        "method_references": _run(
            "method_references",
            [python, "scripts/verify_method_references.py"],
        ),
        "source_registry": _run(
            "source_registry",
            [python, "scripts/verify_sources.py"],
        ),
        "strict_audit": _run("strict_audit", [python, "scripts/verify_strict_audit.py"]),
        "deep_audit": _run("deep_audit", [python, "scripts/verify_deep_audit.py"]),
        "workflow_supply_chain": _run(
            "workflow_supply_chain",
            [python, "scripts/verify_workflows.py"],
        ),
        "docs_links": _run("docs_links", [python, "scripts/verify_docs.py"]),
        "cases": _run(
            "cases",
            [
                python,
                "-m",
                "cutsignal",
                "cases",
                "verify",
                "--output",
                "artifacts/cases.json",
                "--optimizer-seconds",
                "2",
            ],
            timeout=240,
        ),
        "synthetic_evaluation": _run(
            "synthetic_evaluation",
            [
                python,
                "scripts/evaluate_synthetic.py",
                "--output",
                "artifacts/synthetic-evaluation.json",
                "--particles",
                "500",
            ],
            timeout=240,
        ),
        "cli": _run("cli", [python, "-m", "cutsignal", "--help"]),
        "ui": _run("ui", [python, "scripts/ui_smoke.py"], timeout=300),
        "e2e": _run(
            "e2e",
            [python, "scripts/e2e_smoke.py", "--output", "artifacts/e2e"],
            timeout=240,
        ),
    }

    privacy = audit_paths(checkout_files())
    required_docs = [
        "README.md",
        "LICENSE",
        "CONTRIBUTING.md",
        "SECURITY.md",
        "docs/ARCHITECTURE.md",
        "docs/METHODS.md",
        "docs/REFERENCES.md",
        "docs/DEVICE_ADAPTERS.md",
        "docs/DATA_SOURCES.md",
        "docs/PRIVACY.md",
        "docs/LIMITATIONS.md",
        "docs/VALIDATION.md",
        "docs/CASEBOOK.md",
        "docs/PROJECT_AUDIT.md",
        "docs/STRICT_AUDIT.md",
        "docs/DEEP_AUDIT_2026-08-24.md",
        "docs/BENCHMARKS.md",
        "docs/DATA_CARD.md",
        "docs/TUTORIAL.md",
        "docs/TROUBLESHOOTING.md",
        "SUPPORT.md",
        "data/registry/sources.yml",
        "data/registry/method_references.yml",
        "data/registry/claims.yml",
        "data/registry/strict_audit.yml",
        "data/registry/deep_audit.yml",
    ]
    docs = {
        "passed": all(
            (ROOT / relative).is_file() and (ROOT / relative).stat().st_size > 100 for relative in required_docs
        ),
        "required": required_docs,
        "missing": [relative for relative in required_docs if not (ROOT / relative).is_file()],
    }
    semantic_requirements = {
        "README.md": ["share-safe", "cases verify", "not an exhaustive Pareto frontier"],
        "docs/METHODS.md": [
            "linked particle",
            "empirical Bayes",
            "independent post-solve",
            "Method provenance and non-transfer boundary",
        ],
        "docs/REFERENCES.md": [
            "provenance map, not a literature-based validation claim",
            "What they do not establish",
        ],
        "docs/PRIVACY.md": ["private", "share-safe", "does not guarantee anonymity"],
        "docs/CASEBOOK.md": ["deterministic synthetic", "device-overlap-reconciliation"],
        "docs/BENCHMARKS.md": ["Accessed **2026-08-24**", "What is intentionally not copied"],
        "docs/DATA_CARD.md": ["Nonrandom missingness", "not representative samples"],
        "docs/VALIDATION.md": ["known-truth", "recent-weight OLS", "external calibration"],
        "docs/PROJECT_AUDIT.md": ["P0", "P1", "External conditions"],
        "docs/STRICT_AUDIT.md": ["A. Final conclusion", "D. Strict 100-point scorecard", "I. Safe public claims"],
        "docs/DEEP_AUDIT_2026-08-24.md": ["From-zero deep audit", "Frozen baseline", "87/100 local"],
    }
    semantic_missing: list[str] = []
    for relative, phrases in semantic_requirements.items():
        path = ROOT / relative
        content = path.read_text(encoding="utf-8") if path.is_file() else ""
        normalized_content = " ".join(content.casefold().split())
        semantic_missing.extend(
            f"{relative}: {phrase}"
            for phrase in phrases
            if " ".join(phrase.casefold().split()) not in normalized_content
        )
    docs["semantic_requirements"] = semantic_requirements
    docs["semantic_missing"] = semantic_missing
    docs["passed"] = bool(docs["passed"]) and not semantic_missing
    coverage: dict[str, Any] = {}
    coverage_path = ARTIFACTS / "coverage.json"
    if coverage_path.exists():
        coverage = json.loads(coverage_path.read_text(encoding="utf-8")).get("totals", {})
    e2e: dict[str, Any] = {}
    e2e_path = ARTIFACTS / "e2e" / "summary.json"
    if e2e_path.exists():
        e2e = json.loads(e2e_path.read_text(encoding="utf-8"))

    artifact_paths = {
        "coverage": ARTIFACTS / "coverage.json",
        "cases": ARTIFACTS / "cases.json",
        "synthetic_evaluation": ARTIFACTS / "synthetic-evaluation.json",
        "fresh_install": ARTIFACTS / "fresh-install.json",
        "e2e_summary": ARTIFACTS / "e2e" / "summary.json",
    }
    wheels = sorted((ARTIFACTS / "dist").glob("cutsignal-*.whl"))
    source_distributions = sorted((ARTIFACTS / "dist").glob("cutsignal-*.tar.gz"))
    if len(wheels) == 1:
        artifact_paths["wheel"] = wheels[0]
    if len(source_distributions) == 1:
        artifact_paths["source_distribution"] = source_distributions[0]
    artifact_evidence = {name: file_evidence(path) for name, path in artifact_paths.items() if path.is_file()}
    missing_artifacts = sorted(SCORE_CRITICAL_ARTIFACTS.difference(artifact_evidence))
    fresh_install_payload: dict[str, Any] = {}
    fresh_install_path = ARTIFACTS / "fresh-install.json"
    if fresh_install_path.is_file():
        fresh_install_payload = json.loads(fresh_install_path.read_text(encoding="utf-8"))
    wheel_hash_matches_install = bool(
        artifact_evidence.get("wheel")
        and fresh_install_payload.get("wheel_sha256") == artifact_evidence["wheel"]["sha256"]
    )
    artifact_manifest = {
        "passed": not missing_artifacts and wheel_hash_matches_install,
        "required": sorted(SCORE_CRITICAL_ARTIFACTS),
        "missing": missing_artifacts,
        "wheel_hash_matches_fresh_install": wheel_hash_matches_install,
    }

    git_binary = shutil.which("git")
    git_status = (
        subprocess.run(  # noqa: S603
            [git_binary, "status", "--porcelain"],
            cwd=ROOT,
            text=True,
            capture_output=True,
            check=False,
        ).stdout.splitlines()
        if git_binary is not None
        else ["git executable unavailable"]
    )
    git_head = None
    if git_binary is not None:
        head_result = subprocess.run(  # noqa: S603
            [git_binary, "rev-parse", "HEAD"],
            cwd=ROOT,
            text=True,
            capture_output=True,
            check=False,
        )
        if head_result.returncode == 0:
            git_head = head_result.stdout.strip()
    evidence = {
        "schema_version": 1,
        "checkout_fingerprint": checkout_fingerprint(),
        "python": sys.version,
        "platform": sys.platform,
        "git_head": git_head,
        "git_dirty": bool(git_status),
        "git_status_porcelain": git_status,
        "checks": checks,
        "artifacts": artifact_evidence,
        "artifact_manifest": artifact_manifest,
        "coverage": coverage,
        "privacy": privacy.model_dump(mode="json"),
        "documentation": docs,
        "e2e": e2e,
    }
    destination = ARTIFACTS / "verification.json"
    destination.write_text(json.dumps(evidence, indent=2) + "\n", encoding="utf-8")
    passed = (
        all(item["passed"] for item in checks.values())
        and privacy.passed
        and docs["passed"]
        and artifact_manifest["passed"]
    )
    print(f"verification: {'passed' if passed else 'failed'}")
    print(f"evidence: {destination}")
    for name, result in checks.items():
        print(f"- {name}: {'pass' if result['passed'] else 'FAIL'} ({result['duration_seconds']}s)")
    print(f"- privacy: {'pass' if privacy.passed else 'FAIL'} ({len(privacy.findings)} findings)")
    print(f"- documentation: {'pass' if docs['passed'] else 'FAIL'}")
    print(
        f"- artifact manifest: {'pass' if artifact_manifest['passed'] else 'FAIL'} "
        f"({len(artifact_evidence)}/{len(SCORE_CRITICAL_ARTIFACTS)} records)"
    )
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
